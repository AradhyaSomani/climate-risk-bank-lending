"""Coverage report for Person A's hazard tables (Phase 1J), written as Markdown.

    python -m cri.hazard.report --out docs/eval_reports/hazard_coverage.md
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

from cri import config
from cri.geo.districts import load_districts


def _md(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "| " + " | ".join("---" for _ in cols) + " |"]
    for row in df.itertuples(index=False):
        cells = [f"{v:.2f}" if isinstance(v, float) else str(v) for v in row]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def coverage(processed: Path | None = None) -> tuple[str, pd.DataFrame]:
    processed = processed or config.path("processed")
    hz = config.load("hazard")
    d = load_districts()[["district_id", "state"]]
    by = d.groupby("state").size().rename("districts").to_frame()
    notes = []

    f_path = processed / "flood_extent_district_event.parquet"
    if f_path.exists():
        f = pd.read_parquet(f_path)
        f = f[f.source == "gfd"].merge(d, on="district_id")
        hit = f[f.flooded_share > hz["flood"]["event_hit_share"]]
        by["gfd_mapped"] = f.groupby("state").district_id.nunique()
        by["gfd_hit_once"] = hit.groupby("state").district_id.nunique()
        notes.append(
            f"- Global Flood Database: {f.event_id.nunique()} India events, "
            f"{f.district_id.nunique()} of {len(d)} districts inside at least one event "
            f"raster, {hit.district_id.nunique()} flooded above "
            f"{hz['flood']['event_hit_share']:.0%} of their area at least once."
        )
    c_path = processed / "cyclone_exposure_district_event.parquet"
    if c_path.exists():
        c = pd.read_parquet(c_path).merge(d, on="district_id")
        w = c[c.within_radius]
        by["cyclone_exposed_once"] = w.groupby("state").district_id.nunique()
        notes.append(
            f"- IMD best track: {c.event_id.nunique()} storms within "
            f"{hz['cyclone']['max_report_km']} km of a district; {w.event_id.nunique()} storms "
            f"put {w.district_id.nunique()} districts within {hz['cyclone']['radius_km']} km at "
            f"{hz['cyclone']['min_grade']} or stronger."
        )
    b_path = processed / "hazard_baseline_district.parquet"
    if b_path.exists():
        b = pd.read_parquet(b_path).merge(d, on="district_id")
        if "landfall_count" in b:
            by["landfalls"] = b.groupby("state").landfall_count.sum()
        if "perm_water_share" in b:
            miss = int(b.perm_water_share.isna().sum())
            notes.append(f"- Terrain and water layers missing for {miss} districts.")
    by = by.fillna(0).astype(int).reset_index().sort_values("state")
    return "\n".join(notes), by


def write(out: Path) -> Path:
    notes, table = coverage()
    ver = config.load("project").get("data_version", "dev")
    text = (
        "# Hazard table coverage\n\n"
        f"Generated by `python -m cri.hazard.report` (data version `{ver}`). Placeholder "
        "thresholds from `configs/hazard.yaml`.\n\n"
        f"{notes}\n\n## By state\n\n{_md(table)}\n"
    )
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    return out


def main(argv: list[str] | None = None) -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    p.add_argument("--out", type=Path, default=Path("docs/eval_reports/hazard_coverage.md"))
    a = p.parse_args(argv)
    print(write(a.out))


if __name__ == "__main__":
    main()
